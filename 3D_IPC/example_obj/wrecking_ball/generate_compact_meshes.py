#!/usr/bin/env python3
"""Regenerate Example 16's compact closed meshes, retaining source attribution.

The link retains the source stadium dimensions with an eight-station sweep
and a four-sided tube. The gear retains all 18 teeth and the central bore,
using source root/tip samples instead of interior subdivisions.
Run --write to regenerate or --check to verify the checked-in assets.
"""
import argparse
import math
from pathlib import Path


HERE = Path(__file__).resolve().parent


def link_mesh():
    rings = []
    # Keep the cap apexes and both straight-side midpoints exactly.
    for offset, degrees in ((0.25, (0, 90, 180)),
                            (-0.25, (180, 270, 360))):
        for degree in degrees:
            a = math.radians(degree)
            nx, ny = math.cos(a), math.sin(a)
            rings.append((0.4 * nx, offset + 0.4 * ny, nx, ny))
        rings.append((-0.4 if offset > 0 else 0.4, 0.0,
                      -1.0 if offset > 0 else 1.0, 0.0))
    section = ((0.1, 0.0), (0.0, 0.095106),
               (-0.1, 0.0), (0.0, -0.095105))
    vertices = [(x + r * nx, y + r * ny, z)
                for x, y, nx, ny in rings for r, z in section]
    faces = []
    for i in range(8):
        for j in range(4):
            a, b = 4 * i + j, 4 * ((i + 1) % 8) + j
            c, d = 4 * ((i + 1) % 8) + (j + 1) % 4, 4 * i + (j + 1) % 4
            faces.extend(((a, b, c), (a, c, d)))
    return vertices, faces


def gear_mesh():
    # These four points per tooth lie on the authored gear's outline.
    samples = ((7.75, -8.44150964), (10.0, -1.95282289),
               (10.0, 1.95282289), (7.75, 8.44150964))
    contour = []
    for tooth in range(18):
        for radius, offset in samples:
            angle = math.radians(tooth * 20 + offset)
            contour.append((radius * math.cos(angle), radius * math.sin(angle)))
    inner = [(2.7 * math.cos(math.radians(20 * i - 8.44150964)),
              2.7 * math.sin(math.radians(20 * i - 8.44150964))) for i in range(18)]
    vertices = [(x, y, z) for z in (2.0, -2.0) for x, y in contour + inner]
    top = []
    for i in range(18):
        inside, next_inside = 72 + i, 72 + (i + 1) % 18
        for k in range(4):
            a, b = (4 * i + k) % 72, (4 * i + k + 1) % 72
            top.append((inside, a, b))
        top.append((inside, (4 * i + 4) % 72, next_inside))
    faces = top + [(a + 90, c + 90, b + 90) for a, b, c in top]
    for start, count, reverse in ((0, 72, False), (72, 18, True)):
        for i in range(count):
            a, b = start + i, start + (i + 1) % count
            pair = ((a, a + 90, b + 90), (a, b + 90, b))
            faces.extend((a, c, b) if reverse else (a, b, c) for a, b, c in pair)
    return vertices, faces


def obj_text(name, vertices, faces):
    lines = ["# Compact derivative of the existing mesh; retain source licensing.",
             "# Generated by wrecking_ball/generate_compact_meshes.py.",
             f"# {len(vertices)} vertices, {len(faces)} triangles; closed outward surface.",
             "o " + name]
    lines.extend("v " + " ".join(f"{v if abs(v) > 1e-12 else 0:.9f}" for v in p)
                 for p in vertices)
    lines.extend("f " + " ".join(str(i + 1) for i in f) for f in faces)
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument('--write', action='store_true')
    modes.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, name, mesh in ((HERE / 'link_32.obj', 'link_32', link_mesh()),
                             (HERE.parent / 'gear_z18_180.obj', 'gear_z18_180', gear_mesh())):
        content = obj_text(name, *mesh)
        if args.write:
            path.write_text(content)
        elif path.read_text() != content:
            raise SystemExit(f'{path.name} differs from deterministic generation')
        print(f'{path.name}: {len(mesh[0])} vertices, {len(mesh[1])} triangles')


if __name__ == '__main__':
    main()
