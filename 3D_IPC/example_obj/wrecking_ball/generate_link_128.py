#!/usr/bin/env python3
"""Emit the 128-vertex collision mesh derived from the wrecking-ball link.

The source link.obj is a stadium swept with a ten-sided tube. This version
keeps its dimensions but uses 16 longitudinal rings and eight tube samples.
The cap samples are a symmetric subset of the source's 18-degree samples;
the tube samples intersect 45-degree rays with the source decagon. Thus the
new cross section is inscribed, rather than an ellipse that can bulge outside
the source section. Fewer longitudinal segments do change the inner opening
between retained samples; this is not a strict subset of the source solid.

No files are written. Redirect stdout for inspection, use --patch to emit an
apply_patch-compatible new-asset patch, or --check to verify the checked-in
asset. --report emits geometry diagnostics as JSON.
"""

import argparse
import json
import math
from pathlib import Path


CAP_ANGLES_DEG = (0, 36, 72, 90, 108, 144, 180)
CENTERLINE_RADIUS = 0.4
CAP_CENTER_Y = 0.25
TUBE_RADIUS = 0.1
Z_MIN = -0.095105
Z_MAX = 0.095106


def tube_section():
    """Eight samples on the original decagonal tube (radial offset, z)."""
    apothem = TUBE_RADIUS * math.cos(math.pi / 10)
    source_z_extent = TUBE_RADIUS * math.sin(2 * math.pi / 5)
    result = []
    for j in range(8):
        angle = j * math.pi / 4
        dx, dz = math.cos(angle), math.sin(angle)
        candidates = []
        for edge in range(10):
            normal_angle = (edge + 0.5) * math.pi / 5
            projection = dx * math.cos(normal_angle) + dz * math.sin(normal_angle)
            if projection > 1e-14:
                candidates.append(apothem / projection)
        radius = min(candidates)
        radial, z = radius * dx, radius * dz
        z *= (Z_MAX if z >= 0 else -Z_MIN) / source_z_extent
        result.append((radial, z))
    return result


def centerline():
    """Counterclockwise (x, y, radial-x, radial-y) ring descriptions."""
    rings = []
    for degrees in CAP_ANGLES_DEG:
        angle = math.radians(degrees)
        nx, ny = math.cos(angle), math.sin(angle)
        rings.append((CENTERLINE_RADIUS * nx,
                      CAP_CENTER_Y + CENTERLINE_RADIUS * ny, nx, ny))
    rings.append((-CENTERLINE_RADIUS, 0.0, -1.0, 0.0))
    for degrees in CAP_ANGLES_DEG:
        angle = math.radians(degrees + 180)
        nx, ny = math.cos(angle), math.sin(angle)
        rings.append((CENTERLINE_RADIUS * nx,
                      -CAP_CENTER_Y + CENTERLINE_RADIUS * ny, nx, ny))
    rings.append((CENTERLINE_RADIUS, 0.0, 1.0, 0.0))
    return rings


def mesh():
    section = tube_section()
    rings = centerline()
    vertices = []
    for x, y, nx, ny in rings:
        for radial, z in section:
            # Match the emitted mesh, including its decimal precision.
            vertices.append(tuple(round(v, 9) for v in
                                  (x + radial * nx, y + radial * ny, z)))
    faces = []
    for i in range(len(rings)):
        for j in range(len(section)):
            a = i * 8 + j
            b = ((i + 1) % 16) * 8 + j
            c = ((i + 1) % 16) * 8 + (j + 1) % 8
            d = i * 8 + (j + 1) % 8
            faces.extend(((a, b, c), (a, c, d)))
    return vertices, faces


def signed_volume(vertices, faces):
    result = 0.0
    for ia, ib, ic in faces:
        a, b, c = vertices[ia], vertices[ib], vertices[ic]
        result += (a[0] * (b[1] * c[2] - b[2] * c[1])
                   + a[1] * (b[2] * c[0] - b[0] * c[2])
                   + a[2] * (b[0] * c[1] - b[1] * c[0])) / 6
    return result


def obj_text():
    vertices, faces = mesh()
    lines = [
        "# Derived from wrecking_ball/link.obj; retain its attribution/license.",
        "# Generated by generate_link_128.py: 16 rings x 8 tube samples.",
        "# Closed outward-oriented rigid collision surface: 128 vertices, 256 triangles.",
        "o wrecking_ball_link_128",
    ]
    for vertex in vertices:
        # Avoid signed zero so regeneration is byte-stable.
        lines.append("v " + " ".join(f"{v if v else 0.0:.9f}" for v in vertex))
    lines.extend("f " + " ".join(str(i + 1) for i in face) for face in faces)
    return "\n".join(lines) + "\n"


def report():
    vertices, faces = mesh()
    source_vertices, source_faces = [], []
    source = Path(__file__).with_name("link.obj")
    for line in source.read_text().splitlines():
        fields = line.split()
        if fields and fields[0] == "v":
            source_vertices.append(tuple(float(v) for v in fields[1:4]))
        elif fields and fields[0] == "f":
            source_faces.append(tuple(int(v.split("/")[0]) - 1 for v in fields[1:4]))
    bounds = lambda points: [[min(p[i] for p in points), max(p[i] for p in points)]
                             for i in range(3)]
    source_volume = signed_volume(source_vertices, source_faces)
    new_volume = signed_volume(vertices, faces)
    return {
        "source_vertices": len(source_vertices), "vertices": len(vertices),
        "source_triangles": len(source_faces), "triangles": len(faces),
        "source_bounds": bounds(source_vertices), "bounds": bounds(vertices),
        "source_hole_axis_spans": [0.6, 1.1], "hole_axis_spans": [0.6, 1.1],
        "source_signed_volume": source_volume, "signed_volume": new_volume,
        "volume_change_percent": 100 * (new_volume / source_volume - 1),
        "cross_section_radial_z": tube_section(),
        "centerline_x_y_normal_x_normal_y": centerline(),
        "max_cap_segment_degrees": 36,
        "old_cap_segment_degrees": 18,
        "max_inner_chord_inset_vs_source_at_removed_vertex":
            0.3 * (1 - math.cos(math.radians(18))),
        "note": "Dimensions match, but fewer cap chords locally change the opening; "
                "validate neighbor clearance before using a differently arranged net.",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--check", action="store_true")
    modes.add_argument("--patch", action="store_true")
    modes.add_argument("--report", action="store_true")
    args = parser.parse_args()
    text = obj_text()
    if args.check:
        asset = Path(__file__).with_name("link_128.obj")
        if asset.read_text() != text:
            parser.exit(1, "link_128.obj differs from deterministic generation\n")
        print("link_128.obj matches deterministic generation (128 vertices, 256 triangles)")
    elif args.patch:
        print("*** Begin Patch\n*** Add File: example_obj/wrecking_ball/link_128.obj")
        print("\n".join("+" + line for line in text.splitlines()))
        print("*** End Patch")
    elif args.report:
        print(json.dumps(report(), indent=2))
    else:
        print(text, end="")


if __name__ == "__main__":
    main()
